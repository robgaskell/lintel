// Writes src/lib/lint/rules.ts from the installed markdownlint's config schema (Ruling 269).
// The package exports no rule list, so the schema is read as a file. Run after upgrading
// markdownlint: node scripts/gen-lint-rules.mjs. With --stdout it prints instead of writing.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const pkg = `${root}node_modules/markdownlint/`;
const version = JSON.parse(readFileSync(`${pkg}package.json`, 'utf8')).version;
const schema = JSON.parse(readFileSync(`${pkg}schema/markdownlint-config-schema.json`, 'utf8'));

// A rule's description reads "MD004/ul-style : Unordered list style : <url>".
const rules = Object.entries(schema.properties)
  .filter(([key]) => /^MD\d{3}$/.test(key))
  .map(([id, { description }]) => {
    const [names, text] = description.split(' : ');
    const [first, ...aliases] = names.split('/');
    if (first !== id || aliases.length === 0 || !text) throw new Error(`Unexpected schema entry for ${id}`);
    return { id, aliases, description: text };
  });

const q = (text) => JSON.stringify(text);

const lines = [
  `// Generated by scripts/gen-lint-rules.mjs from markdownlint ${version}. Do not edit.`,
  '',
  'export interface LintRule {',
  '  id: string; // "MD004"',
  '  aliases: readonly string[]; // the first is the name settings use',
  '  description: string;',
  '}',
  '',
  'export const LINT_RULES: readonly LintRule[] = [',
  ...rules.map(
    ({ id, aliases, description }) =>
      `  { id: ${q(id)}, aliases: [${aliases.map(q).join(', ')}], description: ${q(description)} },`,
  ),
  '];',
  '',
];
const source = lines.join('\n');

if (process.argv.includes('--stdout')) process.stdout.write(source);
else writeFileSync(`${root}src/lib/lint/rules.ts`, source);
